"""Generate Method C cross-check vectors with the STICK's own code
(overlay/usr/local/lib/sticklink/{pair_qr,noise,crypto}.py + methodc_peer helpers).

All inputs are derived from public labels (sha256("stickdroid-mc-vec/<name>")),
so the file holds test values, not secrets.
Usage: PYTHONPATH=<src>/overlay/usr/local/lib python gen_stick_vectors.py > methodc-stick-v1.json
"""
import hashlib, json, os, sys, urllib.parse
os.environ.setdefault("STICKLINK_TESTING", "1")
from sticklink import pair_qr, noise, crypto
from sticklink.util import b64u

def lab(n, k=32):
    return hashlib.sha256(b"stickdroid-mc-vec/" + n.encode()).digest()[:k]

invite, mbx, home = lab("invite"), lab("mbx", 8), lab("home", 16)
stick_priv, phone_priv = lab("stick-static"), lab("phone-static")
phone_e, stick_e = lab("phone-eph"), lab("stick-eph")
nonce_srv, env_nonce = lab("server-nonce"), lab("env-nonce", 12)
r_i, r_r = lab("r_i"), lab("r_r")
stick_pub = crypto.x25519_public(stick_priv)
phone_pub = crypto.x25519_public(phone_priv)
exp = 1900000000
qr = pair_qr.encode_qr(mailbox_id=mbx, stick_static_pub=stick_pub, invite_secret=invite, exp=exp)
ws = "wss://link.stickllm.com/v1/ws"
join_url = ("https://link.stickllm.com/browser/agent_join.html"
            f"?ws={urllib.parse.quote(ws, safe='')}&qr={urllib.parse.quote(qr, safe='')}")
jk = pair_qr.jk_qr(invite)
mac = pair_qr.join_mac(jk, nonce_srv, mbx)
env_k = pair_qr.env_qr(invite, mbx, home)
th = pair_qr.transcript_hash(mailbox_id=mbx, home_id=home, stick_static_pub=stick_pub)
boot = pair_qr.boot_psk(invite, th)
# methodc_peer.seal_env with a fixed nonce (same AD: enc(mbx)||mbx||dir)
ad = pair_qr.enc(mbx) + mbx + bytes([0x02])
from cryptography.hazmat.primitives.ciphers.aead import ChaCha20Poly1305
offer_pt = json.dumps({"k": "offer", "sdp": "v=0\r\n"}).encode()
env_box = env_nonce + ChaCha20Poly1305(env_k).encrypt(env_nonce, offer_pt, ad)
prologue = b"sl1/qr" + bytes([1]) + home + mbx + stick_pub
ini = noise.Initiator(phone_priv, stick_pub, boot, prologue, e_priv=phone_e)
msg1 = ini.write_msg1()
resp = noise.Responder(stick_priv, prologue, e_priv=stick_e)
rs, _ = resp.read_msg1(msg1)
sess, msg2 = resp.write_msg2(boot)
hh = sess.handshake_hash
psk = pair_qr.pair_psk(r_i=r_i, r_r=r_r, prior=boot, handshake_hash=hh, th=th,
                       initiator_static=rs, responder_static=stick_pub, key_epoch=0)
kc = pair_qr.pair_confirm_kc(psk)
n0, ct0 = sess.encrypt(json.dumps({"t": "r_r", "r": b64u(r_r)}).encode())
frame0 = n0.to_bytes(8, "little") + ct0
H = lambda b: b.hex()
json.dump({
    "_note": "Generated by scripts/methodc/gen_stick_vectors.py from the stick's own pair_qr/noise code. Public-label test values only.",
    "invite": H(invite), "mbx": H(mbx), "home": H(home),
    "stick_priv": H(stick_priv), "stick_pub": H(stick_pub), "phone_priv": H(phone_priv), "phone_pub": H(phone_pub),
    "phone_e": H(phone_e), "server_nonce": H(nonce_srv), "r_i": H(r_i), "r_r": H(r_r), "exp": exp,
    "qr": qr, "join_url": join_url, "jk": H(jk), "join_mac": H(mac), "env_k": H(env_k), "th": H(th), "boot": H(boot),
    "env_box_dir2": H(env_box), "offer_pt": offer_pt.decode(), "prologue": H(prologue),
    "msg1": H(msg1), "msg2": H(msg2), "hh": H(hh), "pair_psk": H(psk), "kc": H(kc),
    "confirm_i": H(pair_qr.confirm_mac(kc, "i", hh)), "confirm_r": H(pair_qr.confirm_mac(kc, "r", hh)),
    "stick_frame0": H(frame0),
}, sys.stdout, indent=1)
